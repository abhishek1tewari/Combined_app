        total_carbs = sum(e["carbs_per_100g"] * e["quantity_g"] / 100 for e in entries)
        total_fat = sum(e["fat_per_100g"] * e["quantity_g"] / 100 for e in entries)
        mc1, mc2, mc3 = st.columns(3)
