# COMBINED HISTORY (food eaten + exercise burned, per day)
# ============================================================
def get_history(user_id, days=10):
    start = (today_local() - timedelta(days=days - 1)).isoformat()
    with get_connection() as conn:
        with conn.cursor() as cur:
            cur.execute("""
                SELECT SUBSTRING(entry_date FROM 1 FOR 10) AS day, SUM(calories) AS total
                FROM food_entries WHERE user_id=%s AND entry_date >= %s
                GROUP BY SUBSTRING(entry_date FROM 1 FOR 10)
            """, (user_id, start))
            consumed = {r["day"]: float(r["total"] or 0) for r in cur.fetchall()}
            cur.execute("""
                SELECT entry_date AS day, SUM(calories_burned) AS burned
                FROM exercise_entries WHERE user_id=%s AND entry_date >= %s
                GROUP BY entry_date
            """, (user_id, start))
            burned = {r["day"]: float(r["burned"] or 0) for r in cur.fetchall()}
    all_days = sorted(set(consumed) | set(burned), reverse=True)
    return [(d, consumed.get(d, 0.0), burned.get(d, 0.0)) for d in all_days]


